interface HelpTooltipProps {
  conceptKey: string;
  className?: string;
  size?: 'sm' | 'md';
  showLabel?: boolean;
  label?: string;
}

export const HelpTooltip: React.FC<HelpTooltipProps> = ({
  conceptKey,
  className = '',
  size = 'sm',
  showLabel = false,
  label = 'What does this mean?',
}) => {
  const [isOpen, setIsOpen] = useState(false);
  const def = CONCEPT_DEFINITIONS[conceptKey];

  if (!def) return null;

  return (
    <span className={clsx('relative inline-flex items-center', className)}>
      <button
        type="button"
        onClick={(e) => {
          e.stopPropagation();
          setIsOpen(!isOpen);
        }}
        className={clsx(
          'transition-colors focus:outline-none flex items-center gap-1',
          showLabel
            ? 'text-[11px] font-semibold text-teal hover:text-teal-dark underline decoration-teal/40 hover:decoration-teal py-0.5 px-1.5 rounded-md hover:bg-teal/5'
            : 'p-1 rounded-full text-slate-400 hover:text-teal hover:bg-teal/10'
        )}
        title={`What is ${def.term}?`}
      >
        <HelpCircle className={size === 'sm' ? 'w-3.5 h-3.5' : 'w-4 h-4'} />
        {showLabel && <span>{label}</span>}
      </button>

      {isOpen && (
        <div
          className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-navy/60 backdrop-blur-sm"
          onClick={() => setIsOpen(false)}
        >
          <div
            className="relative w-full max-w-md bg-navy border border-white/15 rounded-2xl p-6 shadow-2xl text-left"
            onClick={(e) => e.stopPropagation()}
          >
            <div className="flex items-center justify-between pb-3 border-b border-white/10">
              <div className="flex items-center gap-2">
                <span className="p-1.5 rounded-lg bg-teal/20 text-teal">
                  <Info className="w-4 h-4" />
                </span>
                <div>
                  <h4 className="text-sm font-bold text-white">{def.term}</h4>
                  <span className="text-[11px] text-teal font-mono uppercase">{def.simpleName}</span>
                </div>
              </div>
              <button
                type="button"
                onClick={() => setIsOpen(false)}
                className="p-1 rounded-lg text-white/40 hover:text-white hover:bg-white/10"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            <div className="space-y-3.5 pt-4 text-xs">
              <div>
                <span className="text-[10px] font-mono text-white/40 uppercase block">What it is</span>
                <p className="text-white/85 font-light leading-relaxed mt-0.5">{def.whatItIs}</p>
              </div>

              <div>
                <span className="text-[10px] font-mono text-white/40 uppercase block">Why it matters</span>
                <p className="text-white/85 font-light leading-relaxed mt-0.5">{def.whyItMatters}</p>
              </div>

              <div>
                <span className="text-[10px] font-mono text-white/40 uppercase block">Where it comes from</span>
                <p className="text-white/85 font-light leading-relaxed mt-0.5">{def.whereItComesFrom}</p>
              </div>

              <div className="pt-2 border-t border-white/10">
                <span className="text-[10px] font-mono text-gold uppercase block">Recommended action</span>
                <p className="text-gold/90 font-medium leading-relaxed mt-0.5">{def.whatYouShouldDo}</p>
              </div>
            </div>
          </div>
        </div>
      )}
    </span>
  );
};
